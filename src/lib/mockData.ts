export function getNigeriaStateForCity(city: string): string {
  const normalizedCity = city.trim().toLocaleLowerCase()
  if (!normalizedCity) return ''

  return Object.entries(nigeriaCitiesByState).find(([, cities]) =>
    cities.some((knownCity) => knownCity.toLocaleLowerCase() === normalizedCity),
  )?.[0] ?? ''
}
